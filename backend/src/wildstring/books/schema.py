"""Bookshelf tables installed together with the schema 57 storage columns."""

TABLES = (
    """CREATE TABLE IF NOT EXISTS book_libraries (
        id TEXT PRIMARY KEY,
        name TEXT NOT NULL,
        managed_root TEXT NOT NULL UNIQUE,
        storage_mode TEXT NOT NULL DEFAULT 'copy' CHECK(storage_mode IN ('copy','hardlink')),
        default_access TEXT NOT NULL DEFAULT 'restricted' CHECK(default_access IN ('all','restricted')),
        auto_pair INTEGER NOT NULL DEFAULT 1 CHECK(auto_pair IN (0,1)),
        version INTEGER NOT NULL DEFAULT 1,
        created_at REAL NOT NULL,
        updated_at REAL NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS book_library_sources (
        library_id TEXT NOT NULL REFERENCES book_libraries(id) ON DELETE CASCADE,
        id TEXT NOT NULL,
        root TEXT NOT NULL,
        watch_enabled INTEGER NOT NULL DEFAULT 1 CHECK(watch_enabled IN (0,1)),
        PRIMARY KEY(library_id,id),
        UNIQUE(library_id,root)
    )""",
    """CREATE TABLE IF NOT EXISTS book_library_access (
        library_id TEXT NOT NULL REFERENCES book_libraries(id) ON DELETE CASCADE,
        user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        granted_by TEXT REFERENCES users(id) ON DELETE SET NULL,
        created_at REAL NOT NULL,
        PRIMARY KEY(library_id,user_id)
    )""",
    """CREATE TABLE IF NOT EXISTS book_library_migrations (
        id TEXT PRIMARY KEY,
        library_id TEXT NOT NULL REFERENCES book_libraries(id),
        source_root TEXT NOT NULL,
        target_root TEXT NOT NULL,
        library_version INTEGER NOT NULL,
        created_by TEXT NOT NULL,
        target_storage_mode TEXT CHECK(target_storage_mode IN ('copy','hardlink')),
        status TEXT NOT NULL DEFAULT 'queued' CHECK(status IN ('queued','running','failed','completed')),
        copied_files INTEGER NOT NULL DEFAULT 0,
        total_files INTEGER NOT NULL DEFAULT 0,
        copied_bytes INTEGER NOT NULL DEFAULT 0,
        total_bytes INTEGER NOT NULL DEFAULT 0,
        relinked_files INTEGER NOT NULL DEFAULT 0,
        reclaimed_bytes INTEGER NOT NULL DEFAULT 0,
        kept_standalone_files INTEGER NOT NULL DEFAULT 0,
        sidecars_written INTEGER NOT NULL DEFAULT 0,
        error TEXT,
        created_at REAL NOT NULL,
        updated_at REAL NOT NULL
    )""",
    """CREATE UNIQUE INDEX IF NOT EXISTS book_library_migration_active
        ON book_library_migrations(library_id) WHERE status IN ('queued','running')""",
    """CREATE UNIQUE INDEX IF NOT EXISTS book_library_migration_target
        ON book_library_migrations(target_root) WHERE status IN ('queued','running')""",
    """CREATE TABLE IF NOT EXISTS books (
        id TEXT PRIMARY KEY,
        library_id TEXT NOT NULL REFERENCES book_libraries(id) ON DELETE CASCADE,
        managed_dir TEXT NOT NULL,
        title TEXT NOT NULL,
        sort_title TEXT NOT NULL,
        subtitle TEXT,
        authors_json TEXT NOT NULL DEFAULT '[]',
        narrators_json TEXT NOT NULL DEFAULT '[]',
        series_name TEXT,
        series_index REAL,
        publisher TEXT,
        published_year INTEGER,
        language TEXT,
        isbn10 TEXT,
        isbn13 TEXT,
        description TEXT,
        tags_json TEXT NOT NULL DEFAULT '[]',
        cover_path TEXT,
        cover_hash TEXT,
        has_ebook INTEGER NOT NULL DEFAULT 0 CHECK(has_ebook IN (0,1)),
        has_audiobook INTEGER NOT NULL DEFAULT 0 CHECK(has_audiobook IN (0,1)),
        pair_key TEXT,
        overrides_json TEXT NOT NULL DEFAULT '{}',
        locked_fields_json TEXT NOT NULL DEFAULT '[]',
        created_at REAL NOT NULL,
        updated_at REAL NOT NULL,
        UNIQUE(library_id,managed_dir)
    )""",
    """CREATE INDEX IF NOT EXISTS books_by_library_pair ON books(library_id,pair_key)""",
    """CREATE TABLE IF NOT EXISTS book_ebooks (
        id TEXT PRIMARY KEY,
        book_id TEXT NOT NULL UNIQUE REFERENCES books(id) ON DELETE CASCADE,
        format TEXT NOT NULL CHECK(format IN ('epub','txt')),
        managed_path TEXT NOT NULL,
        source_path TEXT,
        link_mode TEXT NOT NULL DEFAULT 'copy' CHECK(link_mode IN ('copy','hardlink','managed_only')),
        file_size INTEGER NOT NULL,
        sha256 TEXT NOT NULL,
        encoding TEXT,
        spine_count INTEGER NOT NULL DEFAULT 0,
        total_chars INTEGER NOT NULL DEFAULT 0,
        cache_key TEXT,
        parsed_at REAL
    )""",
    """CREATE TABLE IF NOT EXISTS book_ebook_chapters (
        book_id TEXT NOT NULL REFERENCES book_ebooks(book_id) ON DELETE CASCADE,
        spine_index INTEGER NOT NULL,
        href TEXT,
        title TEXT NOT NULL,
        level INTEGER NOT NULL,
        block_count INTEGER NOT NULL,
        char_count INTEGER NOT NULL,
        start_global_char INTEGER NOT NULL,
        PRIMARY KEY(book_id,spine_index)
    )""",
    """CREATE TABLE IF NOT EXISTS book_audiobooks (
        id TEXT PRIMARY KEY,
        book_id TEXT NOT NULL UNIQUE REFERENCES books(id) ON DELETE CASCADE,
        is_multi_file INTEGER NOT NULL CHECK(is_multi_file IN (0,1)),
        total_duration_ms INTEGER NOT NULL,
        chapter_count INTEGER NOT NULL,
        total_bytes INTEGER NOT NULL,
        codec_summary TEXT,
        created_at REAL NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS book_audiobook_files (
        book_id TEXT NOT NULL REFERENCES book_audiobooks(book_id) ON DELETE CASCADE,
        file_index INTEGER NOT NULL,
        managed_path TEXT NOT NULL,
        source_path TEXT,
        link_mode TEXT NOT NULL DEFAULT 'copy' CHECK(link_mode IN ('copy','hardlink','managed_only')),
        relative_name TEXT NOT NULL,
        duration_ms INTEGER NOT NULL,
        codec TEXT,
        bitrate INTEGER,
        sample_rate INTEGER,
        channels INTEGER,
        file_size INTEGER NOT NULL,
        sha256 TEXT NOT NULL,
        start_book_ms INTEGER NOT NULL,
        PRIMARY KEY(book_id,file_index)
    )""",
    """CREATE TABLE IF NOT EXISTS book_audiobook_chapters (
        book_id TEXT NOT NULL,
        chapter_index INTEGER NOT NULL,
        file_index INTEGER NOT NULL,
        title TEXT NOT NULL,
        start_file_ms INTEGER NOT NULL,
        end_file_ms INTEGER NOT NULL,
        start_book_ms INTEGER NOT NULL,
        duration_ms INTEGER NOT NULL,
        PRIMARY KEY(book_id,chapter_index),
        FOREIGN KEY(book_id,file_index) REFERENCES book_audiobook_files(book_id,file_index)
            ON DELETE CASCADE
    )""",
    """CREATE TABLE IF NOT EXISTS book_scan_jobs (
        id TEXT PRIMARY KEY,
        library_id TEXT NOT NULL REFERENCES book_libraries(id) ON DELETE CASCADE,
        status TEXT NOT NULL DEFAULT 'queued',
        scanned_files INTEGER NOT NULL DEFAULT 0,
        added_books INTEGER NOT NULL DEFAULT 0,
        updated_books INTEGER NOT NULL DEFAULT 0,
        paired_books INTEGER NOT NULL DEFAULT 0,
        sidecars_applied INTEGER NOT NULL DEFAULT 0,
        error_message TEXT,
        started_at REAL,
        finished_at REAL
    )""",
    """CREATE TABLE IF NOT EXISTS book_reading_progress (
        user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        book_id TEXT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
        spine_index INTEGER NOT NULL,
        block_index INTEGER NOT NULL,
        char_offset INTEGER NOT NULL,
        chapter_title TEXT,
        overall_ratio REAL NOT NULL DEFAULT 0,
        reading_mode TEXT NOT NULL DEFAULT 'scroll' CHECK(reading_mode IN ('scroll','paginated')),
        completed INTEGER NOT NULL DEFAULT 0 CHECK(completed IN (0,1)),
        version INTEGER NOT NULL DEFAULT 0,
        session_id TEXT NOT NULL DEFAULT '',
        device_id TEXT NOT NULL DEFAULT '',
        sequence INTEGER NOT NULL DEFAULT 0,
        updated_at REAL NOT NULL,
        PRIMARY KEY(user_id,book_id)
    )""",
    """CREATE TABLE IF NOT EXISTS book_listening_progress (
        user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        book_id TEXT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
        chapter_index INTEGER NOT NULL,
        chapter_position_ms INTEGER NOT NULL,
        book_position_ms INTEGER NOT NULL,
        playback_rate REAL NOT NULL DEFAULT 1,
        completed INTEGER NOT NULL DEFAULT 0 CHECK(completed IN (0,1)),
        version INTEGER NOT NULL DEFAULT 0,
        session_id TEXT NOT NULL DEFAULT '',
        device_id TEXT NOT NULL DEFAULT '',
        sequence INTEGER NOT NULL DEFAULT 0,
        updated_at REAL NOT NULL,
        PRIMARY KEY(user_id,book_id)
    )""",
    """CREATE TABLE IF NOT EXISTS book_bookmarks (
        id TEXT PRIMARY KEY,
        user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        book_id TEXT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
        kind TEXT NOT NULL CHECK(kind IN ('ebook','audio')),
        spine_index INTEGER,
        block_index INTEGER,
        char_offset INTEGER,
        chapter_index INTEGER,
        position_ms INTEGER,
        excerpt TEXT,
        note TEXT,
        created_at REAL NOT NULL,
        updated_at REAL NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS book_annotations (
        id TEXT PRIMARY KEY,
        user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        book_id TEXT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
        spine_index INTEGER NOT NULL,
        start_block_index INTEGER NOT NULL,
        start_char_offset INTEGER NOT NULL,
        end_block_index INTEGER NOT NULL,
        end_char_offset INTEGER NOT NULL,
        selected_text TEXT NOT NULL,
        note TEXT,
        color TEXT NOT NULL CHECK(color IN ('amber','terracotta','sage','stone')),
        created_at REAL NOT NULL,
        updated_at REAL NOT NULL
    )""",
    """CREATE INDEX IF NOT EXISTS book_bookmarks_by_user_book ON book_bookmarks(user_id,book_id)""",
    """CREATE INDEX IF NOT EXISTS book_annotations_by_user_book ON book_annotations(user_id,book_id)""",
)
